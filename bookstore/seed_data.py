def seed():
    init_db()

    print("→ Добавляю авторов...")
    existing_authors = {a["full_name"] for a in get_authors()}
    for name in AUTHORS:
        if name not in existing_authors:
            add_author(name)

    print("→ Добавляю жанры...")
    existing_genres = {g["name"] for g in get_genres()}
    for name in GENRES:
        if name not in existing_genres:
            try:
                add_genre(name)
            except Exception:
                pass

    genre_map = {g["name"]: g["id"] for g in get_genres()}
    author_map = {a["full_name"]: a["id"] for a in get_authors()}

    print("→ Добавляю книги...")
    con = get_connection(); cur = con.cursor()
    try:
        cur.execute("SELECT title FROM books")
        existing_books = {row[0] for row in cur.fetchall()}
    finally:
        cur.close(); con.close()

    added = 0
    for title, desc, price, year, genre, authors, stock in BOOKS:
        if title in existing_books:
            continue
        genre_id = genre_map.get(genre)
        author_ids = [author_map[a] for a in authors if a in author_map]
        add_book(title, desc, price, year, genre_id, stock,
                 cover_src=None, author_ids=author_ids)
        added += 1

    print(f"✓ Готово. Добавлено книг: {added}")


if __name__ == "__main__":
    seed()